#!/usr/bin/env python3
"""Create patrol_nav/config/nav2_params.yaml from the installed Nav2 default file.

Starting from the default keeps the structure matched to the installed Nav2 version.
Only values for our robot are changed; every change is printed.
"""
import os
import sys
import yaml

try:
    from ament_index_python.packages import get_package_share_directory
    DEFAULT = os.path.join(get_package_share_directory("nav2_bringup"), "params", "nav2_params.yaml")
except Exception:
    DEFAULT = "/opt/ros/jazzy/share/nav2_bringup/params/nav2_params.yaml"

SRC = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser(
    "~/patrol_ws/src/patrol_nav/config/nav2_params.yaml")

# ---- design values (project guide, section 10) ----
BASE_FRAME = "base_footprint"
ROBOT_RADIUS = 0.22
INFLATION_RADIUS = 0.45
MAX_LIN = 0.25
MAX_ANG = 1.0
INIT_X, INIT_Y, INIT_YAW = 0.0, 0.0, 0.0   # robot spawn = SLAM map origin

with open(SRC) as f:
    cfg = yaml.safe_load(f)

changes = []

def put(d, key, value, label):
    old = d.get(key, "<unset>")
    d[key] = value
    changes.append(f"{label}.{key}: {old} -> {value}")

def params(node, sub=None):
    root = cfg.get(node)
    if root is None:
        print(f"WARNING: section '{node}' not found, skipped")
        return None
    p = root["ros__parameters"] if sub is None else root[sub]["ros__parameters"]
    return p

# AMCL
p = params("amcl")
if p is not None:
    put(p, "base_frame_id", BASE_FRAME, "amcl")
    put(p, "scan_topic", "scan", "amcl")
    put(p, "laser_min_range", 0.12, "amcl")
    put(p, "laser_max_range", 8.0, "amcl")
    put(p, "set_initial_pose", True, "amcl")
    put(p, "always_reset_initial_pose", False, "amcl")
    put(p, "initial_pose", {"x": INIT_X, "y": INIT_Y, "z": 0.0, "yaw": INIT_YAW}, "amcl")

# Frames
for node in ("bt_navigator", "behavior_server"):
    p = params(node)
    if p is not None:
        put(p, "robot_base_frame", BASE_FRAME, node)
for node, sub in (("local_costmap", "local_costmap"), ("global_costmap", "global_costmap")):
    p = params(node, sub)
    if p is None:
        continue
    put(p, "robot_base_frame", BASE_FRAME, node)
    put(p, "robot_radius", ROBOT_RADIUS, node)
    if "inflation_layer" in p:
        put(p["inflation_layer"], "inflation_radius", INFLATION_RADIUS, node + ".inflation_layer")

# Controller: replace the heavy default (MPPI) with Regulated Pure Pursuit
p = params("controller_server")
if p is not None:
    old = p.get("FollowPath", {}).get("plugin", "<unset>")
    p["FollowPath"] = {
        "plugin": "nav2_regulated_pure_pursuit_controller::RegulatedPurePursuitController",
        "desired_linear_vel": MAX_LIN,
        "lookahead_dist": 0.6,
        "min_lookahead_dist": 0.3,
        "max_lookahead_dist": 0.9,
        "lookahead_time": 1.5,
        "rotate_to_heading_angular_vel": MAX_ANG,
        "transform_tolerance": 0.2,
        "use_velocity_scaled_lookahead_dist": False,
        "min_approach_linear_velocity": 0.05,
        "approach_velocity_scaling_dist": 0.6,
        "use_collision_detection": True,
        "max_allowed_time_to_collision_up_to_carrot": 1.0,
        "use_regulated_linear_velocity_scaling": True,
        "use_cost_regulated_linear_velocity_scaling": False,
        "regulated_linear_scaling_min_radius": 0.9,
        "regulated_linear_scaling_min_speed": 0.1,
        "use_fixed_curvature_lookahead": False,
        "allow_reversing": False,
        "use_rotate_to_heading": True,
        "rotate_to_heading_min_angle": 0.785,
        "max_angular_accel": 3.2,
        "max_robot_pose_search_dist": 10.0,
    }
    changes.append(f"controller_server.FollowPath.plugin: {old} -> RegulatedPurePursuitController "
                   f"(desired_linear_vel {MAX_LIN})")

# Planner: a goal in unknown space should fail, not be guessed
p = params("planner_server")
if p is not None and "GridBased" in p:
    put(p["GridBased"], "allow_unknown", False, "planner_server.GridBased")

# Velocity smoother limits
p = params("velocity_smoother")
if p is not None:
    put(p, "max_velocity", [MAX_LIN, 0.0, MAX_ANG], "velocity_smoother")
    put(p, "min_velocity", [-MAX_LIN, 0.0, -MAX_ANG], "velocity_smoother")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("# Generated by tools/make_nav2_params.py from the installed Nav2 default file.\n")
    f.write("# Changes: base_footprint frames, radius 0.22, inflation 0.45, 0.25 m/s, RPP controller,\n")
    f.write("# AMCL initial pose (0,0,0) = SLAM map origin = robot spawn point.\n")
    yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)

print(f"Read  : {SRC}")
print(f"Wrote : {OUT}")
for c in changes:
    print("  ", c)
